/**
 * Эвристика «значение вставлено, а не напечатано» для полей формы.
 *
 * В React Native у TextInput нет события onPaste, а чтение буфера
 * обмена требует разрешений и системного диалога на iOS. Поэтому
 * вставка (и автозаполнение менеджером паролей — это тоже готовый
 * ввод) распознается по характеру перехода значения:
 *
 * - рост больше чем на один символ за раз — вставка фрагмента;
 * - длина изменилась и значения расходятся в обе стороны (ни одно не
 *   является префиксом другого) — замена целиком: автозаполнение,
 *   вставка поверх выделения, вставка в середину.
 *
 * Посимвольный ввод, удаление (включая зажатый backspace — предыдущее
 * значение остается префиксом) и замена одного символа той же длины
 * считаются вводом: debounce остается. Ложное «вставка» безвредно —
 * запрос просто уйдет без задержки, дедупликация и кеш сторов поглотят
 * повтор.
 */
export function isPasteLikeInsertion(
  previous: string,
  next: string,
): boolean {
  if (next.length > previous.length + 1) return true;
  if (next.length === previous.length) return false;

  return !next.startsWith(previous) && !previous.startsWith(next);
}
